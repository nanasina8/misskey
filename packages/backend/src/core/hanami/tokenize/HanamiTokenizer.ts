/**
 * 形態素解析の抽象。本命は Lindera、開発・検証・導入前 fallback は Builtin(TinySegmenter 相当)。
 * トレンド軸（[[hanami-tl-osusume-redesign]] step7）はこの抽象越しにトークンを得る。
 *
 * 解析対象は「本文のみ」。URL・ハッシュタグ・メンション・絵文字・メディア情報は呼び出し側で落としてから渡す前提。
 */
// 品詞種別つきトークン。proper=固有名詞（人名/地名/組織/作品/製品名 等）。
export type HanamiTermToken = { term: string; proper: boolean };

export interface HanamiTokenizer {
	readonly name: string;
	/** 利用可能か（Lindera は依存が無ければ false）。 */
	isAvailable(): Promise<boolean>;
	/** 本文を正規化済みトークン配列にする。トレンド用語の候補。 */
	tokenize(text: string): Promise<string[]>;
	/** 固有名詞判定つきトークン。品詞下位分類を持つ実装のみ提供（無ければ Service が proper=false で代替）。 */
	tokenizeWithKind?(text: string): Promise<HanamiTermToken[]>;
}

